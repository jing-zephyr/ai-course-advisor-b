// 动态 System Prompt 注入：按用户身份（学段/角色）追加差异化应答策略
const ROLE_HINTS = [
  { role: '家长', words: ['我孩子', '我家孩子', '我儿子', '我女儿', '家长', '小孩'], hint: '对方是家长视角：优先说明安全保障、师资、作息与费用明细，语气稳重，多给对比信息帮助决策。' },
  { role: '初中学生', words: ['初一', '初二', '初三', '初中'], hint: '对方关注初中学段：夏令营适合初中生的内容、零基础友好度与同龄分组，语言可以更轻快。' },
  { role: '高中学生', words: ['高一', '高二', '高三', '高中', '高考'], hint: '对方关注高中学段：侧重项目实战、作品产出与升学素材价值，尊重其自主决策。' },
  { role: '教师', words: ['我是老师', '我是教师', '我在学校', '任教', '我们学校', '教研室', '校长'], hint: '对方是教师/校方：优先介绍L1-L3分层路径、认证标准与合作院校案例，突出教研含金量与报销凭证等实务信息。' },
  { role: '企业/合作方', words: ['企业', '公司合作', 'B端', '团购', '定制'], hint: '对方是企业或机构合作方：优先引用OPC平台企业合作方案与工作室套餐，说明对接方式。' },
];

function detectRole(text) {
  for (const r of ROLE_HINTS) {
    if (r.words.some((w) => text.includes(w))) return r;
  }
  return null;
}

function formatChunks(chunks) {
  if (!chunks.length) return '\n（本次未检索到相关资料摘录，须按知识边界规则回答「超出资料范围」）\n';
  let out = '';
  chunks.forEach((c, i) => {
    out += `\n[${i + 1}] 《${c.doc}》·${c.chapter}·${c.title}\n${c.content}\n`;
  });
  return out;
}

function buildSystemPrompt(chunks, roleHint) {
  let p = RULES;
  if (roleHint) p += `\n\n## 当前用户画像（动态注入）\n${roleHint.hint}`;
  p += '\n\n## 知识库摘录（本次回答只能依据以下内容；未列出即视为资料中没有）' + formatChunks(chunks);
  return p;
}

module.exports = { RULES, buildSystemPrompt, detectRole };
